export type SoundMaterial = 'grass' | 'dirt' | 'stone' | 'wood' | 'sand' | 'glass' | 'leaves' | 'water';
export type ToolKind = 'none' | 'pickaxe' | 'axe' | 'shovel' | 'sword';

export interface BlockDefinition {
  id: BlockId;
  name: string;
  solid: boolean;
  transparent: boolean;
  cutout?: boolean;
  isPlant?: boolean;
  isRail?: boolean;
  isLiquid?: boolean;
  isItemOnly?: boolean;
  emissive?: boolean;
  hardness: number; // seconds with bare hand; -1 = unbreakable
  preferredTool?: ToolKind;
  sound: SoundMaterial;
  dropId?: BlockId;
  dropCount?: number;
  foodRestore?: number;
  attackDamage?: number;
  miningTier?: number;
  miningSpeed?: number;
  tiles: {
    top: number;
    side: number;
    bottom: number;
    front?: number;
  };
  category: 'natural' | 'building' | 'functional' | 'tools';
}

