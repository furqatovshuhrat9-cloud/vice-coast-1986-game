export function matchCraftingRecipe(
  grid: (InventorySlot | null)[],
  gridSize: 2 | 3
): CraftingRecipe | null {
  const nonEmpty: { r: number; c: number; id: BlockId }[] = [];
  for (let r = 0; r < gridSize; r++) {
    for (let c = 0; c < gridSize; c++) {
      const slot = grid[r * gridSize + c];
      if (slot && slot.count > 0) {
        nonEmpty.push({ r, c, id: slot.id });
      }
    }
  }
  if (nonEmpty.length === 0) return null;

  let minR: number = gridSize, maxR = -1, minC: number = gridSize, maxC = -1;
  for (const item of nonEmpty) {
    if (item.r < minR) minR = item.r;
    if (item.r > maxR) maxR = item.r;
    if (item.c < minC) minC = item.c;
    if (item.c > maxC) maxC = item.c;
  }
  const boxH = maxR - minR + 1;
  const boxW = maxC - minC + 1;

  for (const recipe of CRAFTING_RECIPES) {
    if (recipe.shapeless && recipe.ingredients) {
      if (nonEmpty.length !== recipe.ingredients.length) continue;
      const have = nonEmpty.map((x) => x.id).sort((a, b) => a - b);
      const need = [...recipe.ingredients].sort((a, b) => a - b);
      if (have.every((v, i) => v === need[i])) {
        return recipe;
      }
      continue;
    }

    if (recipe.width !== boxW || recipe.height !== boxH) continue;
    let matches = true;
    for (let r = 0; r < boxH; r++) {
      for (let c = 0; c < boxW; c++) {
        const slot = grid[(minR + r) * gridSize + (minC + c)];
        const expected = recipe.pattern[r * recipe.width + c];
        const actual = slot && slot.count > 0 ? slot.id : null;
        if (actual !== expected) {
          matches = false;
          break;
        }
      }
      if (!matches) break;
    }
    if (matches) return recipe;
  }

  return null;
}

